// Builds api/_demoPhotos.js: one JPEG per demo scenario (api/_demoScenarios.js), base64, for the Demo staging
// page to attach in Procore. A real photo at demo-assets/<ID>.jpg (or .jpeg / .png) wins; otherwise a clearly
// labeled placeholder card with the scenario's caption. Photos are kept out of public/ on purpose: everything
// there is precached by the service worker onto every phone.
// Run: node scripts/build-demo-photos.mjs   (then commit api/_demoPhotos.js)
import fs from "node:fs";
import path from "node:path";
import { createRequire } from "node:module";
import { fileURLToPath } from "node:url";
import { PROJECTS, SCENARIOS } from "../api/_demoScenarios.js";

const root = path.join(path.dirname(fileURLToPath(import.meta.url)), "..");
const sharp = createRequire(import.meta.url)(path.join(root, "functions", "node_modules", "sharp"));
const assets = path.join(root, "demo-assets");

const esc = (s) => String(s).replace(/&/g, "&amp;").replace(/</g, "&lt;").replace(/>/g, "&gt;");
function wrap(text, max) {
  const lines = [];
  let line = "";
  for (const w of String(text).split(/\s+/)) {
    if ((line + " " + w).trim().length > max) { lines.push(line); line = w; } else line = (line + " " + w).trim();
  }
  if (line) lines.push(line);
  return lines;
}

function placeholder(s) {
  const kind = s.recordType === "punch_item" ? "PUNCH ITEM" : "OBSERVATION";
  const title = wrap(s.title, 34).slice(0, 4);
  const words = wrap(`"${s.words}"`, 60).slice(0, 5);
  const t = title.map((l, i) => `<text x="56" y="${250 + i * 58}" font-size="48" font-weight="700" fill="#f5efe6">${esc(l)}</text>`).join("");
  const y0 = 250 + title.length * 58 + 40;
  const w = words.map((l, i) => `<text x="56" y="${y0 + i * 36}" font-size="27" fill="#d8ccbb">${esc(l)}</text>`).join("");
  const svg = `<svg xmlns="http://www.w3.org/2000/svg" width="1024" height="768" font-family="Segoe UI, Arial, sans-serif">
<rect width="1024" height="768" fill="#1c1813"/><rect x="24" y="24" width="976" height="720" rx="28" fill="none" stroke="#ffb81c" stroke-width="6" stroke-dasharray="22 14"/>
<text x="56" y="110" font-size="64" font-weight="800" fill="#ffb81c">${esc(s.id)}</text>
<text x="300" y="104" font-size="30" font-weight="700" fill="#ffc24d">${kind} · ${esc(PROJECTS[s.project].name)}</text>
<text x="56" y="168" font-size="28" fill="#b8ac9c">PLACEHOLDER PHOTO · SiteSnap demo data · fictional</text>
${t}${w}
<text x="56" y="712" font-size="24" fill="#b8ac9c">Replace with a real photo: demo-assets/${esc(s.id)}.jpg, then npm run build:demo-photos</text>
</svg>`;
  return sharp(Buffer.from(svg)).jpeg({ quality: 55 }).toBuffer();
}

const out = {};
const used = [];
for (const s of SCENARIOS) {
  const real = ["jpg", "jpeg", "png"].map((e) => path.join(assets, `${s.id}.${e}`)).find((f) => fs.existsSync(f));
  const buf = real
    ? await sharp(real).rotate().resize(1280, 1280, { fit: "inside", withoutEnlargement: true }).jpeg({ quality: 72 }).toBuffer()
    : await placeholder(s);
  out[s.id] = buf.toString("base64");
  used.push(`${s.id}: ${real ? path.basename(real) : "placeholder"} (${Math.round(buf.length / 1024)} KB)`);
}
const body = `// Generated by scripts/build-demo-photos.mjs: one JPEG (base64) per demo scenario. Don't edit by hand.
// ${used.join("; ")}
export const DEMO_PHOTOS = ${JSON.stringify(out, null, 1)};
export const isPlaceholder = ${JSON.stringify(Object.fromEntries(used.map((u) => [u.slice(0, 5), u.includes("placeholder")])))};
`;
fs.writeFileSync(path.join(root, "api", "_demoPhotos.js"), body);
console.log(used.join("\n"));
